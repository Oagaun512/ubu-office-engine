#!/usr/bin/env node
// Collects the licence texts an engine's browser build must carry into <out-dir>:
//
//   node scripts/licenses.mjs <crate> <out-dir>
//
// - ubu-office-engine/: this repository's LICENSE-MIT, LICENSE-APACHE, NOTICE
// - pdfcraft/: the PDF engine fork's LICENSE-*, NOTICE, ATTRIBUTION.md
// - assets/: bundled-asset notices (Foxit fonts, Adobe CMaps) that cargo cannot see
// - THIRD-PARTY.md: the licence and notice files of every crate linked for wasm32, grouped by
//   identical text so each text appears once with the crates it covers.
import { execFileSync } from "node:child_process";
import { copyFileSync, existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";

const [crate, out] = process.argv.slice(2);
if (!crate || !out) {
  console.error("usage: licenses.mjs <crate> <out-dir>");
  process.exit(2);
}

function copy(from, to) {
  if (!existsSync(from)) throw new Error(`missing licence file ${from}`);
  mkdirSync(dirname(to), { recursive: true });
  copyFileSync(from, to);
}

for (const f of ["LICENSE-MIT", "LICENSE-APACHE", "NOTICE"]) copy(f, join(out, "ubu-office-engine", f));
for (const f of ["LICENSE-MIT", "LICENSE-APACHE", "NOTICE", "ATTRIBUTION.md"]) copy(join("upstream/pdfcraft", f), join(out, "pdfcraft", f));
copy("upstream/pdfcraft/vendor/hayro-interpret/assets/LICENSE_FOXIT", join(out, "assets", "LICENSE_FOXIT"));

const meta = JSON.parse(
  execFileSync("cargo", ["metadata", "--format-version", "1", "--locked", "--filter-platform", "wasm32-unknown-unknown"], {
    encoding: "utf8",
    maxBuffer: 256 * 1024 * 1024,
  }),
);
const byId = new Map(meta.packages.map((p) => [p.id, p]));
const nodes = new Map(meta.resolve.nodes.map((n) => [n.id, n]));
const root = meta.packages.find((p) => p.name === crate && p.source === null);
const seen = new Set();
const stack = [root.id];
while (stack.length) {
  const id = stack.pop();
  if (seen.has(id)) continue;
  seen.add(id);
  for (const dep of nodes.get(id)?.deps ?? []) if (dep.dep_kinds.some((k) => k.kind === null)) stack.push(dep.pkg);
}

// Crates published without a licence file whose text lives in a sibling crate from the same
// repository (alloc-stdlib and alloc-no-stdlib are both github.com/dropbox/rust-alloc-no-stdlib).
const SIBLING = new Map([["alloc-stdlib", "alloc-no-stdlib"]]);
const LICENCE_FILE = /^(LICEN[CS]E|COPYING|NOTICE|COPYRIGHT|UNLICENSE)([-_.].*)?$/i;
const texts = new Map(); // text -> [{crate, file}]
const missing = [];
for (const id of seen) {
  const p = byId.get(id);
  if (p.id === root.id) continue;
  // The pdfcraft crates carry no files of their own; their licence is the fork's, in pdfcraft/.
  if (p.source === null && p.name.startsWith("pdfcraft-")) continue;
  const sibling = SIBLING.has(p.name) && meta.packages.find((q) => q.name === SIBLING.get(p.name) && q.source === p.source);
  const dir = dirname((sibling || p).manifest_path);
  const files = readdirSync(dir).filter((f) => LICENCE_FILE.test(f));
  // Bundled CMap data in hayro-cmap carries Adobe's licence in a subdirectory.
  for (const sub of ["assets", "cmap-resources", "resources"]) {
    const d = join(dir, sub);
    if (existsSync(d)) for (const f of readdirSync(d)) if (LICENCE_FILE.test(f)) files.push(join(sub, f));
  }
  if (!files.length) missing.push(`${p.name} ${p.version} (${p.license})`);
  for (const f of files) {
    // Trailing spaces are dropped (Ubunex's CI rejects whitespace errors); the words are untouched.
    const text = readFileSync(join(dir, f), "utf8").replace(/\r\n/g, "\n").replace(/[ \t]+$/gm, "").trim();
    if (!texts.has(text)) texts.set(text, []);
    texts.get(text).push(`${p.name} ${p.version} — ${f.replaceAll("\\", "/")}`);
  }
}

const sections = [...texts]
  .sort((a, b) => a[1][0].localeCompare(b[1][0]))
  .map(([text, who]) => [`## ${who.length === 1 ? who[0] : `${who.length} crates`}`, "", ...who.map((w) => `- ${w}`), "", "```text", text, "```", ""].join("\n"));
const md = [
  `# Third-party licences: ${crate} (wasm32)`,
  "",
  "The licence and notice files shipped by every crate linked into this build, each distinct text",
  "once, with the crates it covers. Generated by `scripts/licenses.mjs`; the list of crates and",
  "their SPDX expressions is SBOM.md.",
  "",
  "The pdfcraft-* crates are covered by pdfcraft/ next to this file.",
  "",
  ...sections,
].join("\n");
writeFileSync(join(out, "THIRD-PARTY.md"), md);
console.error(`licences: ${texts.size} distinct texts from ${seen.size - 1} crates; ${missing.length} without a file`);
if (missing.length) {
  console.error("crates with no licence file to reproduce (add a SIBLING entry or a vendored text):\n- " + missing.join("\n- "));
  process.exit(1);
}

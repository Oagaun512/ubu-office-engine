#!/usr/bin/env node
// Round-trip and fidelity report over a DOCX corpus (Ubu Office Phase 3, D4).
//
//   node scripts/roundtrip-docx.mjs <roundtrip-binary> <corpus-dir> > ROUNDTRIP.md
//
// Runs ubu-docx's `roundtrip` example once per *.docx under <corpus-dir>, each in its own
// process with a timeout, so a crash or hang is recorded as a result instead of stopping the
// run. Report-only: the exit code is 0 whatever the results, unless the runner itself is broken
// (no files, binary missing). The D4 gate (whether the viewer opens to admins) is decided by a
// person reading this report, not by a threshold here.
import { spawnSync } from "node:child_process";
import { existsSync, readdirSync, statSync } from "node:fs";
import { join, relative } from "node:path";

const [bin, dir] = process.argv.slice(2);
if (!bin || !dir || !existsSync(bin)) {
  console.error("usage: roundtrip-docx.mjs <roundtrip-binary> <corpus-dir>");
  process.exit(2);
}
const TIMEOUT_MS = 60_000;

function walk(d) {
  return readdirSync(d).flatMap((name) => {
    const p = join(d, name);
    return statSync(p).isDirectory() ? walk(p) : name.toLowerCase().endsWith(".docx") ? [p] : [];
  });
}
const files = walk(dir).sort();
if (!files.length) {
  console.error(`no DOCX files under ${dir}`);
  process.exit(2);
}

const results = [];
for (const file of files) {
  const t0 = Date.now();
  const r = spawnSync(bin, [file], { encoding: "utf8", timeout: TIMEOUT_MS, maxBuffer: 16 * 1024 * 1024 });
  const name = relative(dir, file).replaceAll("\\", "/");
  const line = (r.stdout || "").trim().split("\n").pop();
  let res;
  if (r.error?.code === "ETIMEDOUT" || r.signal === "SIGTERM") res = { stage: "timeout", ok: false, error: `no result after ${TIMEOUT_MS / 1000} s` };
  else if (r.status !== 0 || !line) {
    const why = (r.stderr || "").trim().split("\n").filter(Boolean).slice(-3).join(" / ");
    res = { stage: "crash", ok: false, error: `exit ${r.status ?? r.signal}${why ? `: ${why}` : ""}` };
  } else {
    try {
      res = JSON.parse(line);
    } catch {
      res = { stage: "crash", ok: false, error: `unparseable output: ${line.slice(0, 200)}` };
    }
  }
  results.push({ name, ms: Date.now() - t0, ...res });
}

const n = results.length;
const ok = results.filter((r) => r.ok);
const crashes = results.filter((r) => r.stage === "crash" || r.stage === "timeout");
const opened = results.filter((r) => r.stage !== "open" && r.stage !== "read" && r.stage !== "crash" && r.stage !== "timeout");
// Opened, and page 1 rendered with its text layer and a search, and the PDF exported.
const viewed = opened.filter((r) => !["render", "textlayer", "find", "pdf"].includes(r.stage));
const pagesChanged = ok.filter((r) => r.pagesAfter !== r.pages);
const textChanged = ok.filter((r) => r.pagesAfter === r.pages && !r.textSame);
const lossy = results.filter((r) => Array.isArray(r.lost) && r.lost.length);
const lostKinds = new Map();
for (const r of lossy) for (const k of r.lost) lostKinds.set(k, (lostKinds.get(k) ?? 0) + 1);
const byStage = new Map();
for (const r of results.filter((r) => !r.ok)) byStage.set(r.stage, (byStage.get(r.stage) ?? 0) + 1);
const pct = (k) => `${((100 * k) / n).toFixed(1)}%`;
const esc = (s) => String(s ?? "").replaceAll("|", "\\|").replaceAll("\n", " ").slice(0, 300);
const openTimes = opened.map((r) => r.openMs ?? 0).sort((a, b) => a - b);
const pctile = (p) => (openTimes.length ? openTimes[Math.min(openTimes.length - 1, Math.floor((p / 100) * openTimes.length))] : 0);

const out = [
  "# Round-trip and fidelity report: ubu-docx",
  "",
  "Each file: open → render page 1 at 72 dpi → text layer and a search on page 1 → export PDF →",
  "save DOCX → reopen the copy → same page count, same text on every page. One process per file,",
  `${TIMEOUT_MS / 1000} s timeout, \`panic = abort\` as in the browser. Generated by \`scripts/roundtrip-docx.mjs\`.`,
  "",
  `- Files: **${n}**`,
  `- Opened and viewed (render, text layer, search, PDF): **${viewed.length}** (${pct(viewed.length)})`,
  `- Full round trip (saved copy reopens): **${ok.length}** (${pct(ok.length)})`,
  `- Crashes or hangs: **${crashes.length}** (${pct(crashes.length)})`,
  `- Failed: **${n - ok.length}** (${pct(n - ok.length)})`,
  ...[...byStage].sort((a, b) => b[1] - a[1]).map(([stage, k]) => `  - at \`${stage}\`: ${k}`),
  `- Saved copy with a different page count: **${pagesChanged.length}**; same pages but different text: **${textChanged.length}**`,
  `- Saved copy that lost content (what D15 must warn about): **${lossy.length}**`,
  ...[...lostKinds].sort((a, b) => b[1] - a[1]).map(([kind, k]) => `  - ${kind}: ${k}`),
  `- Open time (layout included), opened files: median ${pctile(50)} ms, 95th percentile ${pctile(95)} ms, slowest ${openTimes.at(-1) ?? 0} ms`,
  "",
  "Corpus files are often unusual on purpose (many come from bug reports), so a failure here is a",
  "finding to triage, not necessarily a bug.",
  "",
  "## Failures",
  "",
  "| File | Stage | Error |",
  "|---|---|---|",
  ...results.filter((r) => !r.ok).map((r) => `| \`${esc(r.name)}\` | ${r.stage} | ${esc(r.error)} |`),
  "",
  "## Saved copies that changed",
  "",
  "| File | Pages | Pages after | Text same | Lost |",
  "|---|---|---|---|---|",
  ...results
    .filter((r) => r.ok && (r.pagesAfter !== r.pages || !r.textSame || r.lost?.length))
    .map((r) => `| \`${esc(r.name)}\` | ${r.pages} | ${r.pagesAfter} | ${r.textSame ? "yes" : "no"} | ${esc((r.lost ?? []).join(", "))} |`),
  "",
].join("\n");
process.stdout.write(out);
console.error(`docx round trip: ${ok.length}/${n} ok, ${crashes.length} crashes or hangs, ${lossy.length} lossy saves`);

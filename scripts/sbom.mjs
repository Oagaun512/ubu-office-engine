#!/usr/bin/env node
// SBOM for one engine crate's browser build: every package it links for wasm32, with version,
// licence and source. Fails on copyleft (GPL, AGPL, LGPL, MPL), on a missing licence, and on
// any source other than crates.io or a path inside this repository.
//
//   node scripts/sbom.mjs <crate> > SBOM.md
import { execFileSync } from "node:child_process";
import { relative, resolve } from "node:path";
import { engine } from "./engines.mjs";

const crate = process.argv[2];
if (!crate) {
  console.error("usage: sbom.mjs <crate>");
  process.exit(2);
}

const meta = JSON.parse(
  execFileSync("cargo", ["metadata", "--format-version", "1", "--locked", "--filter-platform", "wasm32-unknown-unknown", "--manifest-path", engine(crate).manifest], {
    encoding: "utf8",
    maxBuffer: 256 * 1024 * 1024,
  }),
);
const byId = new Map(meta.packages.map((p) => [p.id, p]));
const nodes = new Map(meta.resolve.nodes.map((n) => [n.id, n]));
const root = meta.packages.find((p) => p.name === crate && p.source === null);
if (!root) throw new Error(`crate ${crate} is not in the workspace`);

// Normal (linked) dependencies only: build-dependencies and proc macros run at compile time
// and never ship in the .wasm; dev-dependencies are test-only.
const seen = new Set();
const stack = [root.id];
while (stack.length) {
  const id = stack.pop();
  if (seen.has(id)) continue;
  seen.add(id);
  for (const dep of nodes.get(id)?.deps ?? []) {
    if (dep.dep_kinds.some((k) => k.kind === null)) stack.push(dep.pkg);
  }
}

const repo = resolve(".");
const COPYLEFT = /\b(A?GPL|LGPL|MPL)/i;
const errors = [];
const rows = [...seen]
  .map((id) => byId.get(id))
  .filter((p) => p.id !== root.id)
  .sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version))
  .map((p) => {
    const licence = p.license ?? (p.license_file ? `file: ${p.license_file}` : "");
    let source;
    if (p.source === null) {
      source = relative(repo, resolve(p.manifest_path, "..")).replaceAll("\\", "/");
      if (source.startsWith("..")) errors.push(`${p.name}: path dependency outside the repository (${source})`);
    } else if (p.source.startsWith("registry+https://github.com/rust-lang/crates.io-index")) {
      source = "crates.io";
    } else {
      source = p.source;
      errors.push(`${p.name}: unexpected source ${p.source}`);
    }
    if (!p.license) errors.push(`${p.name} ${p.version}: no SPDX licence expression`);
    else if (COPYLEFT.test(p.license) && !/\bOR\b/.test(p.license)) errors.push(`${p.name} ${p.version}: copyleft licence ${p.license}`);
    else if (COPYLEFT.test(p.license)) errors.push(`${p.name} ${p.version}: licence ${p.license} offers copyleft; review and add an explicit choice`);
    return `| ${p.name} | ${p.version} | ${licence} | ${source} |`;
  });

const out = [
  `# SBOM: ${crate} (wasm32-unknown-unknown)`,
  "",
  `Every package linked into the browser build of \`${crate}\` ${root.version}, generated by`,
  "`scripts/sbom.mjs` from `cargo metadata` with the committed `Cargo.lock`. Build-time-only",
  "packages (build scripts, proc macros) and test-only packages are not linked and not listed.",
  "Bundled assets (fonts, CMaps, colour profiles) are not crates; see NOTICE and LICENSES/.",
  "",
  `${rows.length} packages.`,
  "",
  "| Crate | Version | Licence | Source |",
  "|---|---|---|---|",
  ...rows,
  "",
].join("\n");

if (errors.length) {
  console.error("SBOM check FAILED:\n- " + errors.join("\n- "));
  process.exit(1);
}
process.stdout.write(out);

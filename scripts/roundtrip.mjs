#!/usr/bin/env node
// Round-trip report over a PDF corpus.
//
//   node scripts/roundtrip.mjs <roundtrip-binary> <corpus-dir> [manifest.json] > ROUNDTRIP.md
//
// Runs the `roundtrip` example once per *.pdf under <corpus-dir>, each in its own process with
// a timeout, so a crash or hang is recorded as a result instead of stopping the run. The
// optional manifest is pdf.js's test_manifest.json, which supplies passwords for encrypted
// test files. Report-only: the exit code is 0 whatever the results (M1 sets no threshold),
// unless the runner itself is broken (no files, binary missing).
import { spawnSync } from "node:child_process";
import { existsSync, readFileSync, readdirSync, statSync } from "node:fs";
import { basename, join, relative } from "node:path";

const [bin, dir, manifestPath] = process.argv.slice(2);
if (!bin || !dir || !existsSync(bin)) {
  console.error("usage: roundtrip.mjs <roundtrip-binary> <corpus-dir> [manifest.json]");
  process.exit(2);
}
const TIMEOUT_MS = 60_000;

const passwords = new Map();
if (manifestPath && existsSync(manifestPath)) {
  for (const entry of JSON.parse(readFileSync(manifestPath, "utf8"))) {
    if (entry.password && entry.file) passwords.set(basename(entry.file), entry.password);
  }
}

function walk(d) {
  return readdirSync(d).flatMap((name) => {
    const p = join(d, name);
    return statSync(p).isDirectory() ? walk(p) : name.toLowerCase().endsWith(".pdf") ? [p] : [];
  });
}
const files = walk(dir).sort();
if (!files.length) {
  console.error(`no PDFs under ${dir}`);
  process.exit(2);
}

const results = [];
for (const file of files) {
  const args = [file];
  const pw = passwords.get(basename(file));
  if (pw) args.push(pw);
  const t0 = Date.now();
  const r = spawnSync(bin, args, { encoding: "utf8", timeout: TIMEOUT_MS, maxBuffer: 16 * 1024 * 1024 });
  const name = relative(dir, file).replaceAll("\\", "/");
  const line = (r.stdout || "").trim().split("\n").pop();
  let res;
  if (r.error?.code === "ETIMEDOUT" || r.signal === "SIGTERM") res = { stage: "timeout", ok: false, error: `no result after ${TIMEOUT_MS / 1000} s` };
  else if (r.status !== 0 || !line) {
    const why = (r.stderr || "").trim().split("\n").filter(Boolean).slice(-3).join(" / ");
    res = { stage: "crash", ok: false, error: `exit ${r.status ?? r.signal}${why ? `: ${why}` : ""}` };
  } else {
    try {
      res = JSON.parse(line);
    } catch {
      res = { stage: "crash", ok: false, error: `unparseable output: ${line.slice(0, 200)}` };
    }
  }
  results.push({ name, password: Boolean(pw), ms: Date.now() - t0, ...res });
}

const ok = results.filter((r) => r.ok);
const byStage = new Map();
for (const r of results.filter((r) => !r.ok)) byStage.set(r.stage, (byStage.get(r.stage) ?? 0) + 1);
const pct = (n) => `${((100 * n) / results.length).toFixed(1)}%`;
const esc = (s) => String(s ?? "").replaceAll("|", "\\|").replaceAll("\n", " ").slice(0, 300);

const out = [
  "# Round-trip report: ubu-pdf",
  "",
  "Each file: open → render page 1 at 72 dpi → text of page 1 → save (full rewrite) → reopen → same",
  `page count. One process per file, ${TIMEOUT_MS / 1000} s timeout. Generated by \`scripts/roundtrip.mjs\`.`,
  "",
  `- Files: **${results.length}**`,
  `- Full round trip: **${ok.length}** (${pct(ok.length)})`,
  `- Failed: **${results.length - ok.length}** (${pct(results.length - ok.length)})`,
  ...[...byStage].sort((a, b) => b[1] - a[1]).map(([stage, n]) => `  - at \`${stage}\`: ${n}`),
  "",
  "Many corpus files are deliberately broken or unusual (the pdf.js suite tests error handling),",
  "so a failure here is a finding to triage, not necessarily a bug.",
  "",
  "## Failures",
  "",
  "| File | Stage | Error |",
  "|---|---|---|",
  ...results.filter((r) => !r.ok).map((r) => `| \`${esc(r.name)}\` | ${r.stage} | ${esc(r.error)} |`),
  "",
].join("\n");
process.stdout.write(out);
console.error(`round trip: ${ok.length}/${results.length} ok`);
